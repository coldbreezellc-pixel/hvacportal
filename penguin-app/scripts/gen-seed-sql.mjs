#!/usr/bin/env node
// Generates supabase/seed.sql from supabase/seed-data.json (the SEED_DATA constant
// from the original penguin-inventory.html). Item ids follow the original app
// ("pl-0", "fa-3" …) except the two air-filter groups, which the old app both
// labelled "ai-N" (a real bug: a +1 in building 900 also changed building 904).
// They get "f900-N" / "f904-N" here; scripts/import-live.mjs remaps the same way.
//
//   node scripts/gen-seed-sql.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const data = JSON.parse(fs.readFileSync(path.join(here, "../supabase/seed-data.json"), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || v === "" ? "null" : Number(v) || 0);

export const idPrefix = (group) => {
  const m = /^Air Filters\s+(\S+)/.exec(group);
  if (m) return "f" + m[1].toLowerCase();
  return group.slice(0, 2).toLowerCase();
};

const rows = [];
for (const [group, arr] of Object.entries(data)) {
  const prefix = idPrefix(group);
  arr.forEach((r, i) => {
    const id = `${prefix}-${i}`;
    if (group.startsWith("Air Filters") && r.length === 6) {
      // [unitId, qtyUnits, filterSize, qtyPerUnit, total, inStock]
      rows.push(
        `(${q(id)}, ${q(group)}, ${q(r[2])}, '', ${Number(r[5]) || 0}, 0, '', '', ${q(r[0])}, ${n(r[1])}, ${q(String(r[3]))}, ${n(r[4])}, 'Import')`
      );
    } else {
      // [name, partNumber, qty, notes]
      rows.push(
        `(${q(id)}, ${q(group)}, ${q(r[0])}, ${q(r[1] ?? "")}, ${Number(r[2]) || 0}, 0, ${q(r[3] ?? "")}, '', null, null, null, null, 'Import')`
      );
    }
  });
}

const sql = `-- Generated by scripts/gen-seed-sql.mjs — do not edit by hand.
-- ${rows.length} inventory items from the original SEED_DATA.
-- Safe to re-run: existing ids are left untouched.
insert into public.inventory_items
  (id, "group", name, part_number, qty, min_qty, notes, location, unit_id, qty_units, qty_per_unit, total_needed, created_by)
values
${rows.join(",\n")}
on conflict (id) do nothing;
`;

fs.writeFileSync(path.join(here, "../supabase/seed.sql"), sql);
const counts = Object.fromEntries(Object.entries(data).map(([g, a]) => [g, a.length]));
console.log(`Wrote supabase/seed.sql with ${rows.length} items`, counts);
