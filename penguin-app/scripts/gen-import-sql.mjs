#!/usr/bin/env node
// Turns the old portal's live JSON (data/pm_inventory.json, data/pm_logs.json)
// into supabase/import-live.sql — an UPSERT you can paste into the SQL editor.
// No service key needed. Live values win for every item they contain
// (current counts, photos, notes); nothing is deleted.
//
//   node scripts/gen-import-sql.mjs [inventory.json] [logs.json]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const invFile = process.argv[2] || path.join(here, "../../data/pm_inventory.json");
const logFile = process.argv[3] || path.join(here, "../../data/pm_logs.json");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || v === "" ? "null" : Number.parseInt(v, 10) || 0);
const b = (v) => (v ? "true" : "false");
const ts = (v) => (v ? `'${new Date(v).toISOString()}'` : "now()");

// Both air-filter groups used "ai-N" ids in the old app — give each building its own prefix.
const remapId = (i) => {
  const m = /^Air Filters\s+(\S+)/.exec(i.group || "");
  if (m && /^ai-/.test(String(i.id))) return `f${m[1].toLowerCase()}-${String(i.id).slice(3)}`;
  return String(i.id);
};

const items = JSON.parse(fs.readFileSync(invFile, "utf8"));
const rows = items.map((i) => `(${[
  q(remapId(i)), q(i.group || "Misc"), q(i.name || ""), q(i.partNumber || ""),
  Math.max(0, n(i.qty) ?? 0), Math.max(0, n(i.minQty) ?? 0), q(i.notes || ""), q(i.location || ""), q(i.category || ""),
  q(i.photo || null), b(i.photoFailed), q(i.unitId ?? null), n(i.qtyUnits),
  i.qtyPerUnit === undefined || i.qtyPerUnit === null ? "null" : q(String(i.qtyPerUnit)), n(i.totalNeeded),
  q(i.createdBy || "Import"), q(i.updatedBy || null), ts(i.createdAt), ts(i.lastUpdated),
].join(", ")})`);

let sql = `-- Generated by scripts/gen-import-sql.mjs from the Railway portal's live data.
-- ${rows.length} items. Live values win for these ids; nothing is deleted. Safe to re-run.
insert into public.inventory_items
  (id, "group", name, part_number, qty, min_qty, notes, location, category, photo, photo_failed,
   unit_id, qty_units, qty_per_unit, total_needed, created_by, updated_by, created_at, updated_at)
values
${rows.join(",\n")}
on conflict (id) do update set
  "group" = excluded."group", name = excluded.name, part_number = excluded.part_number,
  qty = excluded.qty, min_qty = excluded.min_qty, notes = excluded.notes, location = excluded.location,
  category = excluded.category, photo = coalesce(excluded.photo, public.inventory_items.photo),
  photo_failed = excluded.photo_failed, unit_id = excluded.unit_id, qty_units = excluded.qty_units,
  qty_per_unit = excluded.qty_per_unit, total_needed = excluded.total_needed,
  created_by = excluded.created_by, updated_by = excluded.updated_by,
  created_at = excluded.created_at, updated_at = excluded.updated_at;
`;

if (fs.existsSync(logFile)) {
  const logs = JSON.parse(fs.readFileSync(logFile, "utf8"));
  if (logs.length) {
    const lrows = logs.map((l) => `(${q(String(l.id))}, ${q(l.action || "Note")}, ${q(l.detail || "")}, ${q(l.user || "System")}, null, ${ts(l.ts)})`);
    sql += `
-- ${lrows.length} activity-log entries from the old portal
insert into public.activity_logs (id, action, detail, user_name, user_id, ts)
values
${lrows.join(",\n")}
on conflict (id) do nothing;
`;
  }
}
sql += `
select 'Live import complete: ' || count(*) || ' items, ' || sum(qty) || ' units in stock' as result from public.inventory_items;
`;
const out = path.join(here, "../supabase/import-live.sql");
fs.writeFileSync(out, sql);
console.log(`Wrote ${path.relative(process.cwd(), out)}: ${rows.length} items`);
