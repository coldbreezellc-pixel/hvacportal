#!/usr/bin/env node
// Turns the old portal's data/work_orders.json into supabase/import-work-orders.sql.
// Keeps the original WO numbers (the numbering trigger moves the counter past them).
//
//   node scripts/gen-import-wo-sql.mjs [work_orders.json]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const file = process.argv[2] || path.join(here, "../../data/work_orders.json");
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const ts = (v) => (v ? `'${new Date(v).toISOString()}'` : "now()");
const photos = (arr) => q(JSON.stringify((arr || []).map((p) => (typeof p === "string" ? { thumb: p, full: p } : p))));

const orders = JSON.parse(fs.readFileSync(file, "utf8"));
const woRows = []; const visitRows = [];
for (const w of orders) {
  const id = String(w.id || w.woNumber);
  woRows.push(`(${[q(id), q(w.woNumber || null), q(w.title || "Untitled"), q(w.location || "Other"), q(w.type || "Cold Call"),
    q(w.priority || "Normal"), q(w.status || "Open"), q(w.details || ""), photos(w.photos), q(w.createdBy || null),
    q(w.source || null), q(w.slackChannel || null), q(w.slackTs || null), ts(w.createdAt), ts(w.updatedAt || w.createdAt)].join(", ")})`);
  (w.visits || []).forEach((v, i) => {
    visitRows.push(`(${[q(`${id}-v${i + 1}`), q(id), q(v.date || new Date(v.loggedAt || w.createdAt).toISOString().slice(0, 10)),
      q(v.tech || ""), Number(v.hours) || 0, q(v.notes || ""), photos(v.photos), q(v.tech || null), ts(v.loggedAt)].join(", ")})`);
  });
}

let sql = `-- Generated by scripts/gen-import-wo-sql.mjs from the Railway portal's data/work_orders.json.
-- ${woRows.length} work orders, ${visitRows.length} visits. Safe to re-run (existing ids are left untouched).
insert into public.work_orders
  (id, wo_number, title, location, type, priority, status, details, photos, created_by, source, slack_channel, slack_ts, created_at, updated_at)
values
${woRows.join(",\n")}
on conflict (id) do nothing;
`;
if (visitRows.length) {
  sql += `
insert into public.work_order_visits
  (id, work_order_id, visit_date, tech, hours, notes, photos, logged_by, logged_at)
values
${visitRows.join(",\n")}
on conflict (id) do nothing;
`;
}
sql += `
select 'Work orders imported: ' || count(*) || ' orders, next number will be WO-' || extract(year from now())::int || '-' ||
       lpad(((select coalesce(last, 0) from public.wo_counters where year = extract(year from now())::int) + 1)::text, 4, '0') as result
  from public.work_orders;
`;
const out = path.join(here, "../supabase/import-work-orders.sql");
fs.writeFileSync(out, sql);
console.log(`Wrote ${path.relative(process.cwd(), out)}: ${woRows.length} work orders, ${visitRows.length} visits`);
